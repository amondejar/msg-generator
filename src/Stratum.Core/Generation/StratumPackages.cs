namespace Stratum.Core.Generation;

/// <summary>
/// Where generated services get the Stratum.* packages while they aren't on nuget.org: the stratum tool carries the
/// packages of its own version (stratum-packages next to it) and copies them to a folder that doesn't change between
/// versions (~/.stratum/packages, or STRATUM_PACKAGES). Services point their nuget.config there.
/// </summary>
public static class StratumPackages
{
    public const string EnvironmentVariable = "STRATUM_PACKAGES";

    /// <summary>Key of the source in the nuget.config files Stratum writes.</summary>
    public const string SourceKey = "stratum-local";

    private static readonly Lock Gate = new();
    private static string? _source;
    private static bool _resolved;

    /// <summary>Packages that came with this stratum tool (none when run from the repository).</summary>
    public static string BundledFolder => Path.Combine(AppContext.BaseDirectory, "stratum-packages");

    /// <summary>The folder the services restore Stratum.* from.</summary>
    public static string UserFeed =>
        Environment.GetEnvironmentVariable(EnvironmentVariable) is { Length: > 0 } custom
            ? Path.GetFullPath(custom)
            : Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.UserProfile), ".stratum", "packages");

    /// <summary>
    /// The local folder with this version's Stratum.* packages (copying the bundled ones there first), or null when
    /// there is none: stratum run from the repository without STRATUM_PACKAGES, for instance.
    /// </summary>
    public static string? LocalSource()
    {
        lock (Gate)
        {
            if (_resolved)
            {
                return _source;
            }

            _resolved = true;
            var bundled = Directory.Exists(BundledFolder) ? Directory.GetFiles(BundledFolder, "*.nupkg") : [];
            var custom = Environment.GetEnvironmentVariable(EnvironmentVariable) is { Length: > 0 };
            if ((bundled.Length == 0 || StratumInfo.IsPublished) && !custom)
            {
                return null;
            }

            var feed = UserFeed;
            try
            {
                Directory.CreateDirectory(feed);
                foreach (var package in bundled)
                {
                    var target = Path.Combine(feed, Path.GetFileName(package));
                    if (!File.Exists(target) || new FileInfo(target).Length != new FileInfo(package).Length)
                    {
                        File.Copy(package, target, overwrite: true);
                    }
                }
            }
            catch (Exception e) when (e is IOException or UnauthorizedAccessException)
            {
                return null;
            }

            var has = Directory.EnumerateFiles(feed, $"{StratumInfo.PackagePrefix}ServiceDefaults.{StratumInfo.Version}.nupkg").Any();
            _source = has ? feed : null;
            return _source;
        }
    }

    /// <summary>
    /// Once Stratum.* is on nuget.org, a nuget.config Stratum wrote only for its local packages is in the way (on another
    /// machine, its folder doesn't exist): deletes it when every source but nuget.org is just for Stratum.*.
    /// </summary>
    /// <returns>True when the file was deleted.</returns>
    public static bool RemoveLocalOnlyConfig(string nugetConfig)
    {
        ArgumentNullException.ThrowIfNull(nugetConfig);
        if (!File.Exists(nugetConfig))
        {
            return false;
        }

        var text = File.ReadAllText(nugetConfig);
        if (!text.Contains("Generated by \"stratum", StringComparison.Ordinal))
        {
            return false;
        }

        var patterns = System.Text.RegularExpressions.Regex.Matches(text, "<package pattern=\"(?<p>[^\"]+)\"").Select(m => m.Groups["p"].Value).ToList();
        var sources = System.Text.RegularExpressions.Regex.Matches(text, "<add key=\"[^\"]+\" value=\"(?<v>[^\"]+)\"").Select(m => m.Groups["v"].Value).ToList();
        var onlyStratumBesidesNuGetOrg = patterns.All(p => p is "*" or "Stratum.*" or "StratumKit.*")
            && sources.All(v => v.StartsWith("https://api.nuget.org/", StringComparison.OrdinalIgnoreCase) || !v.Contains("://", StringComparison.Ordinal));
        if (!onlyStratumBesidesNuGetOrg)
        {
            return false;
        }

        File.Delete(nugetConfig);
        return true;
    }

    /// <summary>
    /// Makes <paramref name="nugetConfig"/> restore Stratum.* from <paramref name="source"/>: creates the file, or adds
    /// the source to one Stratum wrote. A nuget.config of your own isn't touched.
    /// </summary>
    /// <returns>True when the file was written.</returns>
    public static bool EnsureSource(string nugetConfig, string source)
    {
        ArgumentNullException.ThrowIfNull(nugetConfig);
        ArgumentNullException.ThrowIfNull(source);
        var full = Path.GetFullPath(source);
        if (!File.Exists(nugetConfig))
        {
            File.WriteAllText(nugetConfig, ServiceGenerator.LocalNuGetConfig(full));
            return true;
        }

        var text = File.ReadAllText(nugetConfig);
        var escaped = System.Security.SecurityElement.Escape(full);
        if (text.Contains($"value=\"{escaped}\"", StringComparison.OrdinalIgnoreCase)
            || !text.Contains("Generated by \"stratum", StringComparison.Ordinal)
            || !text.Contains("</packageSources>", StringComparison.Ordinal)
            || !text.Contains("</packageSourceMapping>", StringComparison.Ordinal))
        {
            return false;
        }

        var nl = text.Contains("\r\n", StringComparison.Ordinal) ? "\r\n" : "\n";
        var key = text.Contains($"key=\"{SourceKey}\"", StringComparison.Ordinal) ? $"{SourceKey}-{StratumInfo.Version}" : SourceKey;
        text = text.Replace("  </packageSources>", $"    <add key=\"{key}\" value=\"{escaped}\" />{nl}  </packageSources>", StringComparison.Ordinal)
            .Replace("  </packageSourceMapping>", $"    <packageSource key=\"{key}\">{nl}      <package pattern=\"{StratumInfo.PackagePrefix}*\" />{nl}    </packageSource>{nl}  </packageSourceMapping>", StringComparison.Ordinal);
        File.WriteAllText(nugetConfig, text);
        return true;
    }
}
