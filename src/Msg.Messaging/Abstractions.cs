namespace Msg.Messaging;

/// <summary>
/// A fact another service may care about ("OrderCreated"). Unlike a domain event it crosses the service
/// boundary, so it is a public contract: add fields, don't rename or remove them.
/// </summary>
public interface IIntegrationEvent
{
    /// <summary>Unique id: consumers use it to process each event only once.</summary>
    Guid EventId { get; }

    DateTimeOffset OccurredAt { get; }
}

/// <summary>Base record for integration events.</summary>
public abstract record IntegrationEvent : IIntegrationEvent
{
    public Guid EventId { get; init; } = Guid.CreateVersion7();

    public DateTimeOffset OccurredAt { get; init; } = DateTimeOffset.UtcNow;
}

/// <summary>
/// Topic of an integration event, shared by publisher and consumers (e.g. "orders.order-created").
/// Without it the topic is the kebab-case type name.
/// </summary>
[AttributeUsage(AttributeTargets.Class, Inherited = false)]
public sealed class IntegrationEventAttribute(string topic) : Attribute
{
    public string Topic { get; } = topic;
}

/// <summary>
/// Publishes integration events. Nothing is sent right away: the event is stored in the outbox in the same
/// transaction as your changes (SaveChanges) and sent to the broker afterwards, with retries.
/// </summary>
public interface IEventBus
{
    ValueTask PublishAsync<TEvent>(TEvent integrationEvent, CancellationToken cancellationToken = default)
        where TEvent : class, IIntegrationEvent;
}

/// <summary>Reacts to an integration event. Runs at most once per event (inbox), with retries if it throws.</summary>
public interface IIntegrationEventHandler<in TEvent>
    where TEvent : class, IIntegrationEvent
{
    Task HandleAsync(TEvent integrationEvent, MessageContext context, CancellationToken cancellationToken);
}

/// <summary>Details of the message being handled.</summary>
/// <param name="Attempt">1 the first time; higher when a previous attempt threw.</param>
public sealed record MessageContext(string MessageId, string Topic, string Source, string? CorrelationId, int Attempt);

/// <summary>
/// Turns domain events into integration events (clean + DDD). Generated by MSG from msg.json: the events you
/// mark as published in the Studio. They are written to the outbox in the same SaveChanges as the aggregate.
/// </summary>
public interface IIntegrationEventMapper
{
    IEnumerable<IIntegrationEvent> Map(object domainEvent);
}
